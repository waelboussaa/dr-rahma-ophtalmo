/**
 * Generates AVIF and WebP siblings of public/brand/logo-clean.png at its own
 * resolution - no resize, no recrop, so the only difference from the PNG is
 * the codec.
 *
 * Run with `npm run logo-formats` whenever logo-clean.png is replaced.
 *
 * WHY THIS EXISTS
 *
 * logo-clean.png is the live brand mark: EyeMark.astro renders it `eager` on
 * every page, at up to three places per page, which makes it one of the
 * heaviest above-the-fold requests on the site relative to its 40-92px
 * display size (71 KB for something that never exceeds 92px).
 *
 * A `public/brand/logo.webp` already existed, generated by
 * scripts/update-brand-logo.mjs from an EARLIER, differently-cropped source
 * than logo-clean.png. A pixel diff against the current logo-clean.png showed
 * a real difference (avg channel diff ~27, not the ~1-5 a same-source WebP
 * recompression would show) and a side-by-side render confirmed it visibly
 * softens the arc's fine strokes. Swapping the live PNG for that file would
 * have traded page-weight for a quality regression on the one mark that's on
 * screen at all times - not an acceptable trade for a few dozen KB. This
 * script instead derives the lighter formats FROM the exact file that ships
 * today, so there is no source mismatch to accidentally reintroduce.
 *
 * logo-clean.png itself is not reproducible from update-brand-logo.mjs (that
 * script never writes a file by this name) - it was produced by an
 * undocumented manual step. Until that's cleaned up, treat logo-clean.png as
 * the source of truth and re-run this script after replacing it.
 */
import sharp from "sharp";
import { fileURLToPath } from "node:url";

const SRC = fileURLToPath(new URL("../public/brand/logo-clean.png", import.meta.url));
const DIR = fileURLToPath(new URL("../public/brand/", import.meta.url));

const png = sharp(SRC);
const meta = await png.metadata();

const [avif, webp] = await Promise.all([
  sharp(SRC).avif({ quality: 90, effort: 6 }).toBuffer(),
  sharp(SRC).webp({ quality: 95 }).toBuffer(),
]);

await Promise.all([
  sharp(avif).toFile(`${DIR}logo-clean.avif`),
  sharp(webp).toFile(`${DIR}logo-clean.webp`),
]);

const pngSize = (await sharp(SRC).toBuffer()).length;
const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`  source  ${meta.width}x${meta.height} png   ${kb(pngSize)}`);
console.log(`  avif    ${kb(avif.length)}`);
console.log(`  webp    ${kb(webp.length)}`);
